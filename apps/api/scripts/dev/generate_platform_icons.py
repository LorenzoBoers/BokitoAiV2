#!/usr/bin/env python3
"""Generate apps/api/app/data/platform_icons.py from lucide-react's icons map.

Run from the repo (needs Node + apps/dashboard/node_modules):

  python apps/api/scripts/dev/generate_platform_icons.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

# …/apps/api/scripts/dev/this.py → repo root
ROOT = Path(__file__).resolve().parents[4]
OUT = ROOT / "apps" / "api" / "app" / "data" / "platform_icons.py"

# Node snippet: PascalCase Lucide keys → kebab-case ids (same rules as the dashboard).
NODE_SNIPPET = r"""
function toKebab(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase();
}
const { icons } = require('lucide-react');
const ids = [...new Set(Object.keys(icons).map(toKebab))].sort();
process.stdout.write(JSON.stringify(ids));
"""


def main() -> int:
    lucide = ROOT / "node_modules" / "lucide-react"
    if not lucide.exists():
        lucide = ROOT / "apps" / "dashboard" / "node_modules" / "lucide-react"
    if not lucide.exists():
        print("lucide-react not installed (repo or apps/dashboard node_modules)", file=sys.stderr)
        return 1
    proc = subprocess.run(
        ["node", "-e", NODE_SNIPPET],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        print(proc.stderr or proc.stdout, file=sys.stderr)
        return proc.returncode or 1
    ids: list[str] = json.loads(proc.stdout)
    if len(ids) < 500:
        print(f"unexpectedly small icon list ({len(ids)})", file=sys.stderr)
        return 1

    lines = [
        '"""Lucide kebab-case icon ids allowed on labels and agent icon marks.',
        "",
        "Generated by apps/api/scripts/dev/generate_platform_icons.py from the",
        "dashboard's lucide-react `icons` map. Re-run after upgrading lucide-react.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "PLATFORM_ICON_IDS: frozenset[str] = frozenset(",
        "    {",
    ]
    for icon_id in ids:
        lines.append(f'        "{icon_id}",')
    lines.extend(
        [
            "    }",
            ")",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(ids)} icons → {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
