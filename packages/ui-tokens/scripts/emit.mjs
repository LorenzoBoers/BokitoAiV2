import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { colorTokens } from '../src/palette.mjs'
import { radius } from '../src/radius.ts'
import { tailwindFontFamily, webFontSize } from '../src/typography.ts'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(packageRoot, '../..')
const cssOut = path.join(repoRoot, 'apps/dashboard/src/styles/tokens.generated.css')
const presetOut = path.join(packageRoot, 'tailwind-preset.generated.cjs')
const themeOut = path.join(packageRoot, 'src/theme.generated.ts')

function cssBlock(selector, mode) {
  const lines = Object.values(colorTokens).map(
    (token) => `  --color-${token.css}: ${token[mode].join(' ')};`,
  )
  const bg = colorTokens.bg[mode]
  const hex = `#${bg.map((n) => n.toString(16).padStart(2, '0')).join('')}`
  lines.push('  --color-cutout: var(--color-bg);')
  lines.push(`  --body-bg: ${hex};`)
  return `${selector} {\n${lines.join('\n')}\n}`
}

function rgb(cssName) {
  return `rgb(var(--color-${cssName}) / <alpha-value>)`
}

function radiusCss(px) {
  if (px === 0) return '0px'
  if (px >= 9999) return '9999px'
  return `${px / 16}rem`
}

function js(value, indent) {
  if (typeof value === 'string') return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map((item) => js(item, indent)).join(', ')}]`
  if (value && typeof value === 'object') {
    const pad = ' '.repeat(indent)
    const inner = ' '.repeat(indent + 2)
    const entries = Object.entries(value).map(([key, item]) => {
      const prop = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key)
      return `${inner}${prop}: ${js(item, indent + 2)}`
    })
    return `{\n${entries.join(',\n')},\n${pad}}`
  }
  return String(value)
}

