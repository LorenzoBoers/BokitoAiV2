import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { colorTokens } from '../src/palette.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const out = path.join(root, 'apps/dashboard/src/styles/tokens.generated.css')

function block(selector, mode) {
  const lines = Object.values(colorTokens).map(
    (token) => `  --color-${token.css}: ${token[mode].join(' ')};`,
  )
  const bg = colorTokens.bg[mode]
  const hex = `#${bg.map((n) => n.toString(16).padStart(2, '0')).join('')}`
  lines.push('  --color-cutout: var(--color-bg);')
  lines.push(`  --body-bg: ${hex};`)
  return `${selector} {\n${lines.join('\n')}\n}`
}

const css = `/* Generated by packages/ui-tokens/scripts/emit-css.mjs. Do not edit. */
${block(':root', 'dark')}

${block(":root[data-theme='light']", 'light')}
`

mkdirSync(path.dirname(out), { recursive: true })
writeFileSync(out, css)
console.log(`wrote ${out}`)
